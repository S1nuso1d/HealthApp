package com.example.healtapp.core.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Шкала размеров интерфейса.
 *
 * Раньше здесь было три значения, и ни на одно из них никто не ссылался: отступы
 * и радиусы писались числами прямо в экранах, поэтому одинаковые по смыслу
 * элементы отличались на 2–4dp. Шаг шкалы — 4dp, промежуточных значений нет
 * намеренно: выбор из ограниченного набора и есть то, что делает вид ровным.
 */
object Dimens {
    // ---- Отступы ----
    /** Между иконкой и текстом, внутри чипа. */
    val SpaceXs = 4.dp
    /** Между строками внутри одного блока. */
    val SpaceS = 8.dp
    /** Между элементами списка, внутренние отступы компактных карточек. */
    val SpaceM = 12.dp
    /** Основной шаг: поля экрана, внутренние отступы карточек. */
    val SpaceL = 16.dp
    /** Между смысловыми блоками на экране. */
    val SpaceXl = 20.dp
    /** Между секциями, отступ под заголовком. */
    val SpaceXxl = 24.dp

    /** Горизонтальные поля контента на всех экранах. */
    val ScreenPadding = SpaceL

    /**
     * Нижний отступ прокручиваемого контента.
     *
     * Нужен, чтобы последний элемент списка не прижимался к нижней навигации
     * и оставался доступным для нажатия.
     */
    val ListBottomPadding = 96.dp

    // ---- Скругления ----
    /** Чипы, бейджи, мелкие индикаторы. */
    val RadiusS = 12.dp
    /** Поля ввода, кнопки, вложенные плитки внутри карточек. */
    val RadiusM = 18.dp
    /** Карточки контента — основной радиус приложения. */
    val RadiusL = 26.dp
    /** Крупные hero-блоки и нижние листы. */
    val RadiusXl = 32.dp

    // ---- Прочее ----
    /** Толщина обводки карточек и полей. */
    val BorderWidth = 1.dp
    /** Подъём карточек: тень должна лишь отделять карточку от фона. */
    val CardElevation = 2.dp
    /** Минимальный размер области нажатия — требование доступности. */
    val MinTouchTarget = 48.dp
    /** Сторона квадратной иконки-бейджа в заголовках и карточках. */
    val IconBadge = 44.dp
    /** Толщина линии и колец на графиках. */
    val ChartStroke = 10.dp
}
